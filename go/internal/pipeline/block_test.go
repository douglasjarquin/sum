func TestRender_carriesTheSummaryAndOneLoggedPassPerRejection(t *testing.T) {
	task := taskFrom(t, `{"schema": 1, "id": "t-a", "brief": "b",
"report": {"candidate": "cccccccccccccccccccccccccccccccccccccccc"},
"evidence": [
{"schema": 1, "id": "e-1", "kind": "review", "source": "reviewer", "at": "2026-01-01T01:00:00+00:00",
"candidate": "dddddddddddddddddddddddddddddddddddddddd", "verdict": "changes-requested",
"text": "the counter is off by one; totals drift; correct the increment",
"notes": [{"kind": "open-finding", "severity": "blocking", "text": "the counter is off by one, so totals drift; correct the increment"}]},
{"schema": 1, "id": "e-2", "kind": "review", "source": "reviewer", "at": "2026-01-01T02:00:00+00:00",
"candidate": "eeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeeee", "verdict": "changes-requested",
"text": "now it double counts",
"notes": [{"kind": "open-finding", "severity": "blocking", "text": "now it double counts, so totals inflate; count each click once"}]},
{"schema": 1, "id": "e-3", "kind": "review", "source": "reviewer", "at": "2026-01-01T03:00:00+00:00",
"candidate": "cccccccccccccccccccccccccccccccccccccccc", "verdict": "approve",
"text": "the count matches the clicks",
"notes": [{"kind": "review-focus", "text": "the count matches the clicks because the increment is applied once per event"}]}]}`)

	block := Render(Derive(task), task)

	if !strings.HasPrefix(block, MarkerStart+"\n## Pipeline\n") || !strings.HasSuffix(block, MarkerEnd+"\n") {
		t.Fatalf("block is not one marked span:\n%s", block)
	}
	for _, want := range []string{
		"> Generated by [sum](https://github.com/douglasjarquin/sum)",
		"| Review | ✅ | Passed after 2 remediation passes |",
		"### Review summary\n\n- **Review focus:** the count matches the clicks because the increment is applied once per event",
		"<details><summary><strong>Review remediation log</strong></summary>",
		"#### Pass 1\n\n- **Open finding:** blocking: the counter is off by one, so totals drift; correct the increment",
		"#### Pass 2\n\n- **Open finding:** blocking: now it double counts, so totals inflate; count each click once",
		"</details>",
	} {
		if !strings.Contains(block, want) {
			t.Fatalf("block is missing %q:\n%s", want, block)
		}
	}
	if strings.Contains(block, "the count matches the clicks\n") {
		t.Fatalf("block published raw findings instead of notes:\n%s", block)
	}
}

