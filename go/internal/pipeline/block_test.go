func TestRender_repeatedRenderDoesNotDuplicateTheSummary(t *testing.T) {
	task := taskFrom(t, `{
"schema": 1, "id": "t-a", "brief": "b",
"evidence": [{"schema": 1, "id": "e-1", "kind": "review", "source": "reviewer", "at": "2026-01-01T01:00:00+00:00",
"verdict": "approve", "notes": [{"kind": "limitation", "text": "source inspected only"}]}]
}`)
	block := Render(Derive(task), task)
	body := "## Summary\n\nhuman\n\n" + block + "\n" + evidenceMarkerStart + "\nevidence\n" + evidenceMarkerEnd + "\n"
	once := splice(body, mustFindBlock(t, body), block)
	twice := splice(once, mustFindBlock(t, once), block)
	if once != twice {
		t.Fatalf("second publish appended:\nfirst:\n%s\nsecond:\n%s", once, twice)
	}
	if strings.Count(twice, "### Review summary") != 1 {
		t.Fatalf("summary duplicated:\n%s", twice)
	}
}

func mustFindBlock(t *testing.T, body string) *span {
	t.Helper()
	at, err := findBlock(body)
	if err != nil {
		t.Fatal(err)
	}
	if at == nil {
		t.Fatal("expected a pipeline block")
	}
	return at
}

func jsonQuote(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch r {
		case '\\', '"':
			b.WriteByte('\\')
			b.WriteRune(r)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		case '\t':
			b.WriteString(`\t`)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}

func TestSplice_keepsEveryByteOutsideTheBlock(t *testing.T) {
	body := "## Summary\n\nHuman prose.\n\n" + MarkerStart + "\nold table\n" + MarkerEnd + "\n\nA closing paragraph.\n"
	at, err := findBlock(body)
	if err != nil {
		t.Fatal(err)
	}

	got := splice(body, at, MarkerStart+"\nnew table\n"+MarkerEnd+"\n")

	want := "## Summary\n\nHuman prose.\n\n" + MarkerStart + "\nnew table\n" + MarkerEnd + "\n\nA closing paragraph.\n"
	if got != want {
		t.Fatalf("splice =\n%q\nwant\n%q", got, want)
	}
}

func TestFindBlock_refusesAMalformedOrDuplicatedSpan(t *testing.T) {
	for name, body := range map[string]string{
		"missing end": MarkerStart + "\ntable\n",
		"inverted":    MarkerEnd + "\ntable\n" + MarkerStart,
		"two blocks":  MarkerStart + "a" + MarkerEnd + "\n" + MarkerStart + "b" + MarkerEnd,
	} {
		if _, err := findBlock(body); err == nil {
			t.Fatalf("%s: findBlock accepted a malformed body", name)
		}
	}
	at, err := findBlock("no markers here")
	if err != nil || at != nil {
		t.Fatalf("findBlock on a plain body = %v, %v", at, err)
	}
}
