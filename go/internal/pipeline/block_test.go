func TestRender_replacesAVerboseLegacyReportLikeNicebaas212(t *testing.T) {
	legacy := `# Independent review: t-385bb2b02667 (nicebaas#168)

Verdict: **approve**
Candidate: ` + "`f8a88c8b00b295f545558bdc93bbb7720094207e`" + `

## Intent vs issue #168

The three-dot diff vs origin/main is the two scoped files.

## Tests

The hero locator is scoped to header.

## Declared checks (plausible)

| Check | Plausible? |
| mise exec -- pnpm --dir=apps/frontend check | Yes |

## Evidence

Run 20260924T110449Z-28368 scenario landing-nav-hero.
`
	task := taskFrom(t, `{
"schema": 1, "id": "t-a", "brief": "b",
"evidence": [{"schema": 1, "id": "e-1", "kind": "review", "source": "reviewer", "at": "2026-01-01T01:00:00+00:00",
"verdict": "approve", "text": `+jsonQuote(legacy)+`}]
}`)

	authored := "## Summary\n\nAligns the landing header.\n\n## Test plan\n\n- [x] Playwright landing shell\n\n"
	oldBlock := MarkerStart + "\n## Pipeline\n\nold table\n\n### Review summary\n\n" + legacy + MarkerEnd
	evidence := "\n\n" + evidenceMarkerStart + "\n### Before/after evidence\n\ncaptured pair\n" + evidenceMarkerEnd + "\n"
	body := authored + oldBlock + evidence

	block := Render(Derive(task), task)
	at, err := findBlock(body)
	if err != nil {
		t.Fatal(err)
	}
	got := splice(body, at, block)
	again := splice(got, mustFindBlock(t, got), block)

	if !strings.HasPrefix(got, authored) {
		t.Fatalf("authored summary was rewritten:\n%s", got)
	}
	if !strings.Contains(got, evidenceMarkerStart+"\n### Before/after evidence\n\ncaptured pair\n"+evidenceMarkerEnd) {
		t.Fatalf("evidence block was rewritten:\n%s", got)
	}
	if strings.Contains(got, "Independent review") || strings.Contains(got, "Declared checks") || strings.Contains(got, "Intent vs issue") {
		t.Fatalf("legacy #212 report survived republish:\n%s", got)
	}
	if !strings.Contains(got, "- **Limitation:** "+legacyNotesLimitation) {
		t.Fatalf("legacy republish did not disclose the missing notes:\n%s", got)
	}
	if got != again {
		t.Fatalf("republish was not idempotent")
	}
}

